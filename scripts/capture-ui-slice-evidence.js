#!/usr/bin/env node

/**
 * Capture UI Slice Evidence
 *
 * Captures BEFORE, TARGET, AFTER screenshots for visual evidence.
 * Also generates manifest metadata for the slice.
 *
 * Usage:
 *   node scripts/capture-ui-slice-evidence.js \
 *     --phase "2.1" \
 *     --slice "A" \
 *     --route "http://localhost:3000" \
 *     --target "reference/screenshots/proben-mvp-6/hero-target-light-1.png" \
 *     --output-dir "test-results/visual-review"
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

// Parse command line arguments
const args = process.argv.slice(2);
const flags = {};
for (let i = 0; i < args.length; i += 2) {
  const flag = args[i].replace('--', '');
  flags[flag] = args[i + 1] || '';
}

const config = {
  phase: flags.phase || '2.1',
  slice: flags.slice || 'A',
  route: flags.route || 'http://localhost:3000',
  target: flags.target || '',
  outputDir: flags['output-dir'] || 'test-results/visual-review',
  viewport: flags.viewport || '1280,720',
  timestamp: new Date().toISOString(),
  branch: getGitBranch(),
  commit: getGitCommit()
};

function getGitBranch() {
  try {
    return execSync('git rev-parse --abbrev-ref HEAD', { encoding: 'utf-8' }).trim();
  } catch {
    return 'unknown';
  }
}

function getGitCommit() {
  try {
    return execSync('git rev-parse --short HEAD', { encoding: 'utf-8' }).trim();
  } catch {
    return 'unknown';
  }
}

// Ensure output directory exists
if (!fs.existsSync(config.outputDir)) {
  fs.mkdirSync(config.outputDir, { recursive: true });
}

// Generate file paths
const sliceSlug = `phase-${config.phase.replace('.', '-')}-slice-${config.slice.toLowerCase()}`;
const beforePath = path.join(config.outputDir, `${sliceSlug}-before.png`);
const afterPath = path.join(config.outputDir, `${sliceSlug}-after.png`);
const manifestPath = path.join(config.outputDir, `${sliceSlug}-manifest.json`);
const diffPath = path.join(config.outputDir, `${sliceSlug}-diff.png`);

console.log(`📸 Capturing UI Slice Evidence`);
console.log(`\nPhase: ${config.phase}`);
console.log(`Slice: ${config.slice}`);
console.log(`Route: ${config.route}`);
console.log(`Viewport: ${config.viewport}`);
console.log(`Branch: ${config.branch}`);
console.log(`Commit: ${config.commit}`);
console.log(`Timestamp: ${config.timestamp}`);

// Check if dev server is running
console.log(`\n🔍 Checking if dev server is running...`);
try {
  const response = execSync(`curl -s -o /dev/null -w "%{http_code}" ${config.route}`, { encoding: 'utf-8', timeout: 5000 });
  if (response !== '200') {
    console.error(`❌ Dev server not responding (got ${response}). Start with: npm run dev`);
    process.exit(1);
  }
  console.log(`✅ Dev server is running`);
} catch (error) {
  console.error(`❌ Cannot reach ${config.route}. Start dev server with: npm run dev`);
  process.exit(1);
}

// Capture AFTER screenshot (current implementation)
console.log(`\n📸 Capturing AFTER screenshot...`);
try {
  execSync(
    `npx playwright screenshot ${config.route} ${afterPath} --viewport-size=${config.viewport}`,
    { stdio: 'inherit', timeout: 30000 }
  );
  console.log(`✅ AFTER screenshot: ${afterPath}`);
} catch (error) {
  console.error(`❌ Failed to capture AFTER screenshot:`, error.message);
  process.exit(1);
}

// Check if BEFORE screenshot exists (from previous run or backup)
if (fs.existsSync(beforePath)) {
  console.log(`✅ BEFORE screenshot exists: ${beforePath}`);
} else {
  console.log(`⚠️  BEFORE screenshot not found: ${beforePath}`);
  console.log(`   (This is expected for first run. Create backup if needed.)`);
}

// Check if TARGET screenshot exists
const targetExists = config.target && fs.existsSync(config.target);
if (targetExists) {
  console.log(`✅ TARGET screenshot exists: ${config.target}`);
} else {
  console.log(`⚠️  TARGET screenshot not found: ${config.target}`);
}

// Create manifest
const manifest = {
  phase: config.phase,
  slice: config.slice,
  route: config.route,
  viewport: config.viewport,
  browser: 'chromium',
  timestamp: config.timestamp,
  gitBranch: config.branch,
  gitCommit: config.commit,
  screenshots: {
    target: config.target || null,
    before: fs.existsSync(beforePath) ? beforePath : null,
    after: afterPath,
    diff: null // Will be generated by generate-visual-diff.js
  },
  report: path.join(config.outputDir, `${sliceSlug}.html`),
  tests: {
    domBlockers: null, // Will be populated by test run
    visualAssertions: null
  },
  verdict: 'PENDING_REVIEW'
};

fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
console.log(`\n📋 Manifest created: ${manifestPath}`);

console.log(`\n✅ Evidence capture complete!`);
console.log(`\nNext steps:`);
console.log(`  1. Run DOM blocker tests: npm test -- slice-a-header-parity`);
console.log(`  2. Generate visual diff: node scripts/generate-visual-diff.js`);
console.log(`  3. Generate HTML report: node scripts/generate-visual-review-report.js`);
console.log(`  4. Open report in browser to complete review`);
